import { readdir, readFile, writeFile, access } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { Script } from 'node:vm';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const sourceRoot = path.join(root, 'src');
const require = createRequire(import.meta.url);
const { APP_VERSION } = require('../src/room/types.js');

async function collect(directory, prefix = '') {
    const files = [];
    for (const entry of await readdir(directory, { withFileTypes: true })) {
        const id = prefix + entry.name;
        if (entry.isDirectory())
            files.push(...await collect(path.join(directory, entry.name), id + '/'));
        else if (entry.isFile() && entry.name.endsWith('.js'))
            files.push(id);
    }
    return files.sort();
}

const ids = await collect(sourceRoot);
const modules = new Map(await Promise.all(ids.map(async id => [id, await readFile(path.join(sourceRoot, id), 'utf8')])));
if (!modules.has('main.js'))
    throw Error('Missing src/main.js');
for (const [id, source] of modules) {
    new Script(source, { filename: id });
    for (const match of source.matchAll(/\brequire\(["']([^"']+)["']\)/g)) {
        const target = path.posix.normalize(path.posix.join(path.posix.dirname(id), match[1]));
        if (!match[1].startsWith('.') || !modules.has(target))
            throw Error(`Unbundled dependency in ${id}: ${match[1]}`);
    }
}
const loader = `const cache=Object.create(null);
function load(id){if(cache[id])return cache[id].exports;if(!modules[id])throw Error('Missing module: '+id);const module={exports:{}};cache[id]=module;modules[id](p=>{if(!p.startsWith('.'))throw Error('External require: '+p);const parts=(id.slice(0,id.lastIndexOf('/')+1)+p).split('/'),out=[];for(const part of parts){if(part==='..')out.pop();else if(part!=='.'&&part)out.push(part);}return load(out.join('/'));},module,module.exports);return module.exports;}
load('main.js');`;
const bundle = `(()=>{'use strict';\nconst modules={\n${[...modules].map(([id, source]) => `${JSON.stringify(id)}:function(require,module,exports){\n${source.trimEnd()}\n}`).join(',\n')}\n};\n${loader}\n})();`;
new Script(bundle, { filename: 'hx.html bundle' });
const template = await readFile(path.join(sourceRoot, 'page.html'), 'utf8');
const marker = '<!-- GAME_BUNDLE -->';
if (template.split(marker).length !== 2)
    throw Error('src/page.html must contain exactly one GAME_BUNDLE marker');
const html = template.replace(marker, `<script>/* 人类杀 v${APP_VERSION} | source: src/ | generated by scripts/build.mjs */\n${bundle.replace(/<\/script/gi, '<\\/script')}\n</script>`);
// Pages overlays public/ onto _site/. A second hx.html there would silently
// replace the reviewed output, so reject this duplicate in both build modes.
if (await access(path.join(root, 'public/hx.html')).then(() => true, () => false))
    throw Error('Remove duplicate public/hx.html; hx.html is the sole generated entry point');
const output = path.join(root, 'hx.html');
if (process.argv.includes('--check')) {
    if (await readFile(output, 'utf8') !== html)
        throw Error('hx.html is stale; run npm run build and commit the generated file');
    console.log(`Build verified: ${ids.length} modules, v${APP_VERSION}`);
} else {
    await writeFile(output, html);
    console.log(`Built hx.html: ${ids.length} modules, v${APP_VERSION}`);
}
